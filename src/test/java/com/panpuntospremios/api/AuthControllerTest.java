    @Test
    void testLogoutRequiereCsrfYAutenticacionValida() throws Exception {
        // 1. Sin CSRF token -> 403 Forbidden
        mockMvc.perform(post("/api/v1/auth/logout"))
            .andExpect(status().isForbidden());

        // 2. Con autenticación pero sin CSRF token -> 403 Forbidden
        mockMvc.perform(post("/api/v1/auth/logout")
                .with(user("1")))
            .andExpect(status().isForbidden());

        // 3. Con CSRF pero sin autenticación -> 401 Unauthorized
        mockMvc.perform(post("/api/v1/auth/logout")
                .with(csrf()))
            .andExpect(status().isUnauthorized())
            .andExpect(content().string(containsString("Debe iniciar sesión")));

        // 4. Con CSRF y autenticación -> 200 OK
        mockMvc.perform(post("/api/v1/auth/logout")
                .with(user("1"))
                .with(csrf()))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.mensaje").value("Sesión cerrada correctamente"));
    }

    @Test
    void testClientCooldownImpideGeneracionDeSegundoToken() throws Exception {
        SolicitudAccesoDTO dto = new SolicitudAccesoDTO("verificado@panpuntos.com");

        // 1. Primera solicitud: 200 OK y registra 1 token
        mockMvc.perform(post("/api/v1/auth/access-requests")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(dto)))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.mensaje").value(AuthService.MENSAJE_GENERICO_SOLICITUD));

        try (Connection con = dataSource.getConnection();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM cliente_token_acceso")) {
            assertTrue(rs.next());
            assertEquals(1, rs.getInt(1));
        }

        // 2. Segunda solicitud inmediata (en cooldown de 60s): 200 OK (anti-enumeración), pero NO genera nuevo token
        mockMvc.perform(post("/api/v1/auth/access-requests")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(dto)))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.mensaje").value(AuthService.MENSAJE_GENERICO_SOLICITUD));

        try (Connection con = dataSource.getConnection();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM cliente_token_acceso")) {
            assertTrue(rs.next());
            assertEquals(1, rs.getInt(1), "El cooldown de 60s debe evitar generar un segundo token");
        }
    }

    @Test
    void testIpRateLimiterBloqueaExcesoDeSolicitudesCon429() throws Exception {
        SolicitudAccesoDTO dto = new SolicitudAccesoDTO("inexistente@correo.com");
        String ipPrueba = "203.0.113.195";

        // Consumir las 10 solicitudes permitidas por la ventana
        for (int i = 0; i < 10; i++) {
            mockMvc.perform(post("/api/v1/auth/access-requests")
                    .header("X-Forwarded-For", ipPrueba)
                    .contentType(MediaType.APPLICATION_JSON)
                    .content(objectMapper.writeValueAsString(dto)))
                .andExpect(status().isOk());
        }

        // La solicitud número 11 debe ser bloqueada con 429 Too Many Requests
        mockMvc.perform(post("/api/v1/auth/access-requests")
                .header("X-Forwarded-For", ipPrueba)
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(dto)))
            .andExpect(status().isTooManyRequests())
            .andExpect(jsonPath("$.status").value(429))
            .andExpect(jsonPath("$.error").value("Too Many Requests"))
            .andExpect(jsonPath("$.mensaje").value(containsString("Ha superado el límite de solicitudes permitidas")));
    }

