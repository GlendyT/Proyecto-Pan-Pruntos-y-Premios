    @Test
    void testConsumirTokenValidoIniciaSesionYRechazaReuso() throws Exception {
        String rawToken = "token-secreto-de-prueba-1234567890";
        String tokenHash = AuthService.calcularSha256(rawToken);

        // Insertar token válido en BD
        try (Connection con = dataSource.getConnection();
             Statement st = con.createStatement()) {
            st.execute(String.format("""
                INSERT INTO cliente_token_acceso (id_cliente, token_hash, fecha_creacion, fecha_expiracion)
                VALUES (1, '%s', CURRENT_TIMESTAMP, TIMESTAMPADD(MINUTE, 15, CURRENT_TIMESTAMP))
            """, tokenHash));
        }

        ConsumirTokenDTO dto = new ConsumirTokenDTO(rawToken);

        // 1. Primer consumo: Debe ser 200 OK y devolver datos del cliente
        mockMvc.perform(post("/api/v1/auth/consume")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(dto)))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.mensaje").value("Sesión iniciada correctamente"))
            .andExpect(jsonPath("$.identificador").value("CLI-ACTIVO-VERIF"))
            .andExpect(jsonPath("$.nombre").value("Cliente Verificado"))
            .andExpect(jsonPath("$.email").value("verificado@panpuntos.com"));

        // 2. Segundo consumo (reúso del mismo token): Debe retornar 401 Unauthorized
        mockMvc.perform(post("/api/v1/auth/consume")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(dto)))
            .andExpect(status().isUnauthorized())
            .andExpect(jsonPath("$.status").value(401))
            .andExpect(jsonPath("$.mensaje").value("El enlace de acceso es inválido o ha expirado."));
    }

