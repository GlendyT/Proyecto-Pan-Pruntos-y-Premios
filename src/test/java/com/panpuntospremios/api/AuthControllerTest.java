    @BeforeEach
    void setupDatabase() throws Exception {
        ipRateLimiter.resetear();
        try (Connection con = dataSource.getConnection();
             Statement st = con.createStatement()) {

            st.execute("DROP TABLE IF EXISTS cliente_token_acceso CASCADE");
            st.execute("DROP TABLE IF EXISTS cliente CASCADE");

            st.execute("""
                CREATE TABLE cliente (
                    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    identificador VARCHAR(20) NOT NULL UNIQUE,
                    nombre VARCHAR(100) NOT NULL,
                    telefono VARCHAR(20),
                    email VARCHAR(100),
                    saldo_puntos INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL,
                    fecha_registro DATE DEFAULT CURRENT_DATE NOT NULL,
                    email_verificado CHAR(1) DEFAULT 'N' NOT NULL,
                    fecha_verificacion_email TIMESTAMP NULL
                )
            """);

            st.execute("""
                CREATE TABLE cliente_token_acceso (
                    id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_cliente INTEGER NOT NULL,
                    token_hash VARCHAR(64) NOT NULL UNIQUE,
                    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    fecha_expiracion TIMESTAMP NOT NULL,
                    fecha_uso TIMESTAMP NULL,
                    direccion_ip VARCHAR(45) NULL,
                    origen_solicitud VARCHAR(100) NULL,
                    CONSTRAINT fk_token_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
                )
            """);

            // Cliente 1: Activo y con email verificado
            st.execute("""
                INSERT INTO cliente (identificador, nombre, telefono, email, saldo_puntos, activo, email_verificado)
                VALUES ('CLI-ACTIVO-VERIF', 'Cliente Verificado', '55551111', 'verificado@panpuntos.com', 50, 'S', 'S')
            """);

            // Cliente 2: Activo pero NO verificado
            st.execute("""
                INSERT INTO cliente (identificador, nombre, telefono, email, saldo_puntos, activo, email_verificado)
                VALUES ('CLI-NO-VERIF', 'Cliente No Verificado', '55552222', 'noverificado@panpuntos.com', 0, 'S', 'N')
            """);

            // Cliente 3: Inactivo
            st.execute("""
                INSERT INTO cliente (identificador, nombre, telefono, email, saldo_puntos, activo, email_verificado)
                VALUES ('CLI-INACTIVO', 'Cliente Inactivo', '55553333', 'inactivo@panpuntos.com', 0, 'N', 'S')
            """);
        }
    }

    @Test
    void testSolicitarAccesoClienteVerificadoGeneraTokenYDevuelveMensajeGenerico() throws Exception {
        SolicitudAccesoDTO dto = new SolicitudAccesoDTO("verificado@panpuntos.com");

        mockMvc.perform(post("/api/v1/auth/access-requests")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(dto)))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.mensaje").value(AuthService.MENSAJE_GENERICO_SOLICITUD));

        // Validar que se generó 1 token en la base de datos
        try (Connection con = dataSource.getConnection();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM cliente_token_acceso")) {
            assertTrue(rs.next());
            assertEquals(1, rs.getInt(1), "Debe haberse registrado un token para el cliente verificado");
        }
    }

