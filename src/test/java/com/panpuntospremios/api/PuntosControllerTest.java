package com.panpuntospremios.api;

import com.panpuntospremios.api.modelo.ClientePrincipal;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.authority.AuthorityUtils;
import org.springframework.test.context.TestPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;

import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.authentication;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest(classes = ApiApplication.class)
@AutoConfigureMockMvc
@TestPropertySource(properties = {
    "spring.datasource.url=jdbc:h2:mem:test_points_api;MODE=Oracle;DB_CLOSE_DELAY=-1",
    "spring.datasource.username=sa",
    "spring.datasource.password=",
    "spring.datasource.driver-class-name=org.h2.Driver"
})
class PuntosControllerTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private DataSource dataSource;

    @BeforeEach
    void prepararEsquema() throws Exception {
        try (Connection con = dataSource.getConnection();
             Statement st = con.createStatement()) {
            st.execute("DROP TABLE IF EXISTS movimiento_puntos CASCADE");
            st.execute("DROP TABLE IF EXISTS cliente CASCADE");
            st.execute("""
                CREATE TABLE cliente (
                    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    identificador VARCHAR(20) NOT NULL UNIQUE,
                    nombre VARCHAR(100) NOT NULL,
                    telefono VARCHAR(20),
                    email VARCHAR(100),
                    saldo_puntos INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL
                )
            """);
            st.execute("""
                CREATE TABLE movimiento_puntos (
                    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_cliente INTEGER NOT NULL,
                    fecha TIMESTAMP NOT NULL,
                    tipo VARCHAR(15) NOT NULL,
                    puntos INTEGER NOT NULL,
                    referencia VARCHAR(50),
                    CONSTRAINT fk_mov_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
                )
            """);
            st.execute("""
                INSERT INTO cliente (id_cliente, identificador, nombre, saldo_puntos, activo)
                VALUES (1, 'CLI-1', 'Cliente Uno', 42, 'S')
            """);
            st.execute("""
                INSERT INTO cliente (id_cliente, identificador, nombre, saldo_puntos, activo)
                VALUES (2, 'CLI-2', 'Cliente Dos', 999, 'S')
            """);
            st.execute("""
                INSERT INTO cliente (id_cliente, identificador, nombre, saldo_puntos, activo)
                VALUES (3, 'CLI-3', 'Cliente Inactivo', 88, 'N')
            """);
            st.execute("""
                INSERT INTO movimiento_puntos (id_movimiento, id_cliente, fecha, tipo, puntos, referencia)
                VALUES (1, 1, TIMESTAMP '2026-01-01 10:00:00', 'ACUMULACION', 10, 'PEDIDO:1')
            """);
            st.execute("""
                INSERT INTO movimiento_puntos (id_movimiento, id_cliente, fecha, tipo, puntos, referencia)
                VALUES (2, 1, TIMESTAMP '2026-01-02 10:00:00', 'CANJE', 5, 'CANJE:2')
            """);
            st.execute("""
                INSERT INTO movimiento_puntos (id_movimiento, id_cliente, fecha, tipo, puntos, referencia)
                VALUES (3, 1, TIMESTAMP '2026-01-02 10:00:00', 'ACUMULACION', 20, 'PEDIDO:3')
            """);
            st.execute("""
                INSERT INTO movimiento_puntos (id_movimiento, id_cliente, fecha, tipo, puntos, referencia)
                VALUES (4, 2, TIMESTAMP '2026-01-03 10:00:00', 'ACUMULACION', 999, 'PRIVADO')
            """);
        }
    }

    @Test
    void endpointsDeClienteRequierenSesion() throws Exception {
        mockMvc.perform(get("/api/v1/me"))
            .andExpect(status().isUnauthorized());
        mockMvc.perform(get("/api/v1/me/points"))
            .andExpect(status().isUnauthorized());
        mockMvc.perform(get("/api/v1/me/points/movements"))
            .andExpect(status().isUnauthorized());
    }

    @Test
    void perfilYSaldoSeDerivanDelPrincipalYNoDeParametrosDelNavegador() throws Exception {
        mockMvc.perform(get("/api/v1/me")
                .with(authentication(autenticacionCliente(1)))
                .param("idCliente", "2"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.idCliente").value(1))
            .andExpect(jsonPath("$.nombre").value("Cliente Uno"));

        mockMvc.perform(get("/api/v1/me/points")
                .with(authentication(autenticacionCliente(1)))
                .param("idCliente", "2"))
            .andExpect(status().isOk())
            .andExpect(header().string("Cache-Control", org.hamcrest.Matchers.containsString("no-store")))
            .andExpect(jsonPath("$.saldoPuntos").value(42));
    }

    @Test
    void historialPaginaConCursorEstableYFiltraSoloAlClienteDeSesion() throws Exception {
        String primeraRespuesta = mockMvc.perform(get("/api/v1/me/points/movements")
                .with(authentication(autenticacionCliente(1)))
                .param("limit", "2"))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.movimientos.length()").value(2))
            .andExpect(jsonPath("$.movimientos[0].idMovimiento").value(3))
            .andExpect(jsonPath("$.movimientos[1].idMovimiento").value(2))
            .andExpect(jsonPath("$.hayMas").value(true))
            .andExpect(jsonPath("$.movimientos[0].idCliente").doesNotExist())
            .andReturn().getResponse().getContentAsString();

        String cursor = new com.fasterxml.jackson.databind.ObjectMapper()
            .readTree(primeraRespuesta).get("siguienteCursor").asText();

        mockMvc.perform(get("/api/v1/me/points/movements")
                .with(authentication(autenticacionCliente(1)))
                .param("limit", "2")
                .param("before", cursor))
            .andExpect(status().isOk())
            .andExpect(jsonPath("$.movimientos.length()").value(1))
            .andExpect(jsonPath("$.movimientos[0].idMovimiento").value(1))
            .andExpect(jsonPath("$.hayMas").value(false))
            .andExpect(jsonPath("$.siguienteCursor").doesNotExist());
    }

    @Test
    void validaLimiteCursorYClienteActivo() throws Exception {
        mockMvc.perform(get("/api/v1/me/points/movements")
                .with(authentication(autenticacionCliente(1)))
                .param("limit", "101"))
            .andExpect(status().isBadRequest());

        mockMvc.perform(get("/api/v1/me/points/movements")
                .with(authentication(autenticacionCliente(1)))
                .param("before", "cursor-invalido"))
            .andExpect(status().isBadRequest());

        mockMvc.perform(get("/api/v1/me/points")
                .with(authentication(autenticacionCliente(3))))
            .andExpect(status().isNotFound());
    }

    private UsernamePasswordAuthenticationToken autenticacionCliente(int idCliente) {
        ClientePrincipal principal = new ClientePrincipal(
            idCliente,
            "CLI-" + idCliente,
            "Cliente " + idCliente,
            "cliente" + idCliente + "@example.test"
        );
        return UsernamePasswordAuthenticationToken.authenticated(
            principal,
            null,
            AuthorityUtils.NO_AUTHORITIES
        );
    }
}
