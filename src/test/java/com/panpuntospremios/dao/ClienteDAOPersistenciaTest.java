package com.panpuntospremios.dao;

import com.panpuntospremios.modelo.Cliente;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

class ClienteDAOPersistenciaTest {

    private static final String URL = "jdbc:h2:mem:clientes;MODE=Oracle;DB_CLOSE_DELAY=-1";

    @BeforeEach
    void prepararEsquema() throws Exception {
        try (Connection conexion = DriverManager.getConnection(URL);
             Statement sentencia = conexion.createStatement()) {
            sentencia.execute("DROP TABLE IF EXISTS cliente");
            sentencia.execute("""
                CREATE TABLE cliente (
                    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    identificador VARCHAR(20) NOT NULL UNIQUE,
                    nombre VARCHAR(100) NOT NULL,
                    telefono VARCHAR(20),
                    email VARCHAR(100),
                    saldo_puntos INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL,
                    fecha_registro DATE DEFAULT CURRENT_DATE NOT NULL
                )
                """);
        }
    }

    @Test
    void conservaRegistroEdicionYDesactivacionAlReabrirLaConexion() throws Exception {
        Cliente nuevo = new Cliente(
            0,
            "CLI-REAPERTURA",
            "Cliente inicial",
            "55550000",
            "inicial@correo.com",
            0,
            true,
            null
        );

        try (Connection conexion = DriverManager.getConnection(URL)) {
            new ClienteDAOImpl(conexion).registrar(nuevo);
        }

        int idCliente;
        try (Connection conexionReabierta = DriverManager.getConnection(URL)) {
            ClienteDAO dao = new ClienteDAOImpl(conexionReabierta);
            Cliente guardado = dao.buscarPorIdentificador("CLI-REAPERTURA");

            assertNotNull(guardado);
            assertEquals("Cliente inicial", guardado.getNombre());
            idCliente = guardado.getIdCliente();

            Cliente editado = new Cliente(
                idCliente,
                guardado.getIdentificador(),
                "Cliente editado",
                "55551111",
                "editado@correo.com",
                guardado.getSaldoPuntos(),
                true,
                guardado.getFechaRegistro()
            );
            dao.actualizar(editado);
        }

        try (Connection segundaReapertura = DriverManager.getConnection(URL)) {
            ClienteDAO dao = new ClienteDAOImpl(segundaReapertura);
            Cliente editado = dao.buscarPorIdentificador("CLI-REAPERTURA");

            assertEquals("Cliente editado", editado.getNombre());
            assertEquals("55551111", editado.getTelefono());
            assertEquals("editado@correo.com", editado.getEmail());
            dao.desactivar(idCliente);
        }

        try (Connection terceraReapertura = DriverManager.getConnection(URL)) {
            ClienteDAO dao = new ClienteDAOImpl(terceraReapertura);

            assertTrue(dao.listarActivos().isEmpty());
        }
    }
}
