package com.panpuntospremios.dao;

import com.panpuntospremios.modelo.Cliente;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.sql.*;
import java.util.HexFormat;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class ClienteTokenAccesoCompatibilidadTest {

    private static final String URL = "jdbc:h2:mem:cliente_token_acceso;MODE=Oracle;DB_CLOSE_DELAY=-1";
    private Connection conexion;

    @BeforeEach
    void setup() throws Exception {
        conexion = DriverManager.getConnection(URL);
        try (Statement st = conexion.createStatement()) {
            st.execute("DROP TABLE IF EXISTS cliente_token_acceso CASCADE");
            st.execute("DROP TABLE IF EXISTS cliente CASCADE");

            // Esquema original existente antes de Fase 1
            st.execute("""
                CREATE TABLE cliente (
                    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    identificador VARCHAR(20) NOT NULL UNIQUE,
                    nombre VARCHAR(100) NOT NULL,
                    telefono VARCHAR(20),
                    email VARCHAR(100),
                    saldo_puntos INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL,
                    fecha_registro DATE DEFAULT CURRENT_DATE NOT NULL
                )
            """);

            // Datos existentes en producción
            st.execute("""
                INSERT INTO cliente (identificador, nombre, telefono, email, saldo_puntos, activo)
                VALUES ('CLI-EXISTENTE-01', 'Cliente Preexistente', '55551234', 'cliente@example.com', 100, 'S')
            """);
        }
    }

    @AfterEach
    void tearDown() throws Exception {
        if (conexion != null && !conexion.isClosed()) {
            conexion.close();
        }
    }

    @Test
    void testMigracionAditivaPreservaDatosYCompatibilidadConClienteDAO() throws Exception {
        // 1. Aplicar migración aditiva Fase 1 UP
        try (Statement st = conexion.createStatement()) {
            st.execute("""
                ALTER TABLE cliente ADD (
                    email_verificado CHAR(1) DEFAULT 'N' NOT NULL,
                    fecha_verificacion_email TIMESTAMP NULL
                )
            """);

            st.execute("""
                CREATE TABLE cliente_token_acceso (
                    id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_cliente INTEGER NOT NULL,
                    token_hash VARCHAR(64) NOT NULL UNIQUE,
                    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    fecha_expiracion TIMESTAMP NOT NULL,
                    fecha_uso TIMESTAMP NULL,
                    direccion_ip VARCHAR(45) NULL,
                    origen_solicitud VARCHAR(100) NULL,
                    CONSTRAINT fk_token_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
                )
            """);
        }

        // 2. Verificar que los datos preexistentes conservan valores y toman DEFAULT 'N'
        try (Statement st = conexion.createStatement();
             ResultSet rs = st.executeQuery("SELECT identificador, saldo_puntos, email_verificado FROM cliente WHERE identificador = 'CLI-EXISTENTE-01'")) {
            assertTrue(rs.next(), "El cliente preexistente debe existir");
            assertEquals("CLI-EXISTENTE-01", rs.getString("identificador"));
            assertEquals(100, rs.getInt("saldo_puntos"));
            assertEquals("N", rs.getString("email_verificado"), "Clientes previos deben tener email_verificado='N' por defecto");
        }

        // 3. Verificar que ClienteDAOImpl funciona normalmente sin ninguna modificación de código
        ClienteDAO dao = new ClienteDAOImpl(conexion);

        Cliente existente = dao.buscarPorIdentificador("CLI-EXISTENTE-01");
        assertNotNull(existente);
        assertEquals("Cliente Preexistente", existente.getNombre());

        Cliente nuevo = new Cliente(
            0,
            "CLI-NUEVO-02",
            "Cliente Nuevo Swing",
            "55555678",
            "nuevo@example.com",
            0,
            true,
            null
        );
        dao.registrar(nuevo);

        Cliente guardado = dao.buscarPorIdentificador("CLI-NUEVO-02");
        assertNotNull(guardado);
        assertEquals("Cliente Nuevo Swing", guardado.getNombre());

        guardado.setNombre("Cliente Nuevo Editado");
        dao.actualizar(guardado);
        Cliente editado = dao.buscarPorIdentificador("CLI-NUEVO-02");
        assertEquals("Cliente Nuevo Editado", editado.getNombre());

        List<Cliente> activos = dao.listarActivos();
        assertEquals(2, activos.size());

        dao.desactivar(editado.getIdCliente());
        List<Cliente> activosDespues = dao.listarActivos();
        assertEquals(1, activosDespues.size());
    }

    @Test
    void testCicloDeVidaDeTokensYConsumoUnico() throws Exception {
        // Aplicar migración aditiva Fase 1 UP
        try (Statement st = conexion.createStatement()) {
            st.execute("""
                ALTER TABLE cliente ADD (
                    email_verificado CHAR(1) DEFAULT 'N' NOT NULL,
                    fecha_verificacion_email TIMESTAMP NULL
                )
            """);

            st.execute("""
                CREATE TABLE cliente_token_acceso (
                    id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_cliente INTEGER NOT NULL,
                    token_hash VARCHAR(64) NOT NULL UNIQUE,
                    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    fecha_expiracion TIMESTAMP NOT NULL,
                    fecha_uso TIMESTAMP NULL,
                    direccion_ip VARCHAR(45) NULL,
                    origen_solicitud VARCHAR(100) NULL,
                    CONSTRAINT fk_token_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
                )
            """);
        }

        // Obtener id del cliente existente
        int idCliente;
        try (Statement st = conexion.createStatement();
             ResultSet rs = st.executeQuery("SELECT id_cliente FROM cliente WHERE identificador = 'CLI-EXISTENTE-01'")) {
            assertTrue(rs.next());
            idCliente = rs.getInt(1);
        }

        // Generar hash SHA-256 de un token simulado
        String rawToken = "secreto-aleatorio-seguro-token-123456";
        MessageDigest digest = MessageDigest.getInstance("SHA-256");
        String tokenHash = HexFormat.of().formatHex(digest.digest(rawToken.getBytes(StandardCharsets.UTF_8)));

        // Insertar token válido por 15 minutos
        Timestamp ahora = new Timestamp(System.currentTimeMillis());
        Timestamp expiracion = new Timestamp(System.currentTimeMillis() + (15 * 60 * 1000));

        String sqlInsert = """
            INSERT INTO cliente_token_acceso (id_cliente, token_hash, fecha_creacion, fecha_expiracion, direccion_ip, origen_solicitud)
            VALUES (?, ?, ?, ?, ?, ?)
        """;
        try (PreparedStatement ps = conexion.prepareStatement(sqlInsert)) {
            ps.setInt(1, idCliente);
            ps.setString(2, tokenHash);
            ps.setTimestamp(3, ahora);
            ps.setTimestamp(4, expiracion);
            ps.setString(5, "192.168.1.10");
            ps.setString(6, "Mozilla/5.0");
            int filas = ps.executeUpdate();
            assertEquals(1, filas);
        }

        // Primer consumo: debe ser exitoso (1 fila actualizada de manera atómica)
        String sqlConsumo = """
            UPDATE cliente_token_acceso
               SET fecha_uso = CURRENT_TIMESTAMP
             WHERE token_hash = ?
               AND fecha_uso IS NULL
               AND fecha_expiracion > CURRENT_TIMESTAMP
        """;
        try (PreparedStatement ps = conexion.prepareStatement(sqlConsumo)) {
            ps.setString(1, tokenHash);
            int filasConsumidas = ps.executeUpdate();
            assertEquals(1, filasConsumidas, "El token debe consumirse exactamente una vez");
        }

        // Segundo consumo: debe fallar (0 filas actualizadas, protegiendo contra reuso)
        try (PreparedStatement ps = conexion.prepareStatement(sqlConsumo)) {
            ps.setString(1, tokenHash);
            int reuso = ps.executeUpdate();
            assertEquals(0, reuso, "Un token consumido no puede volverse a utilizar");
        }
    }

    @Test
    void testReversibilidadDeMigracionDown() throws Exception {
        // 1. Aplicar UP
        try (Statement st = conexion.createStatement()) {
            st.execute("ALTER TABLE cliente ADD (email_verificado CHAR(1) DEFAULT 'N' NOT NULL, fecha_verificacion_email TIMESTAMP NULL)");
            st.execute("""
                CREATE TABLE cliente_token_acceso (
                    id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_cliente INTEGER NOT NULL,
                    token_hash VARCHAR(64) NOT NULL UNIQUE,
                    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    fecha_expiracion TIMESTAMP NOT NULL,
                    fecha_uso TIMESTAMP NULL,
                    direccion_ip VARCHAR(45) NULL,
                    origen_solicitud VARCHAR(100) NULL,
                    CONSTRAINT fk_token_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
                )
            """);
        }

        // 2. Aplicar DOWN (Rollback)
        try (Statement st = conexion.createStatement()) {
            st.execute("DROP TABLE cliente_token_acceso CASCADE");
            st.execute("ALTER TABLE cliente DROP COLUMN email_verificado");
            st.execute("ALTER TABLE cliente DROP COLUMN fecha_verificacion_email");
        }

        // 3. Confirmar que los datos de cliente siguen intactos
        try (Statement st = conexion.createStatement();
             ResultSet rs = st.executeQuery("SELECT identificador, saldo_puntos FROM cliente WHERE identificador = 'CLI-EXISTENTE-01'")) {
            assertTrue(rs.next());
            assertEquals("CLI-EXISTENTE-01", rs.getString("identificador"));
            assertEquals(100, rs.getInt("saldo_puntos"));
        }
    }
}
