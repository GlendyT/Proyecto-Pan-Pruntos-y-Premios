package com.panpuntospremios.servicio;

import com.panpuntospremios.dao.MovimientoInventarioDAOImpl;
import com.panpuntospremios.dao.ProductoDAOImpl;
import com.panpuntospremios.excepcion.ValidacionException;
import com.panpuntospremios.modelo.MovimientoInventario;
import com.panpuntospremios.modelo.Producto;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class InventarioServicioTest {

    @Test
    void abasteceYRegistraMovimientoEnLaMismaTransaccion() throws Exception {
        try (Connection conexion = crearBase("inventario_exitoso", false)) {
            InventarioServicio servicio = servicio(conexion);

            servicio.abastecer(1, 3);

            assertEquals(8, existencia(conexion));
            List<MovimientoInventario> movimientos = servicio.listarMovimientos();
            assertEquals(1, movimientos.size());
            assertEquals("ABASTECIMIENTO", movimientos.get(0).getTipo());
            assertEquals(3, movimientos.get(0).getCantidad());
            assertEquals(8, movimientos.get(0).getExistenciaResultante());
        }
    }

    @Test
    void revierteExistenciaSiFallaElRegistroDelMovimiento() throws Exception {
        try (Connection conexion = crearBase("inventario_rollback", true)) {
            InventarioServicio servicio = servicio(conexion);

            assertThrows(SQLException.class, () -> servicio.abastecer(1, 3));

            assertEquals(5, existencia(conexion));
            assertEquals(0, cantidadMovimientos(conexion));
        }
    }

    @Test
    void rechazaCantidadCeroONegativa() throws Exception {
        try (Connection conexion = crearBase("inventario_cantidad", false)) {
            InventarioServicio servicio = servicio(conexion);

            assertThrows(ValidacionException.class, () -> servicio.abastecer(1, 0));
            assertThrows(ValidacionException.class, () -> servicio.abastecer(1, -2));
            assertEquals(5, existencia(conexion));
        }
    }

    private Connection crearBase(String nombre, boolean forzarFalloMovimiento) throws Exception {
        Connection conexion = DriverManager.getConnection("jdbc:h2:mem:" + nombre + ";MODE=Oracle");
        try (Statement st = conexion.createStatement()) {
            st.execute("""
                CREATE TABLE producto (
                    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo VARCHAR(20) NOT NULL UNIQUE,
                    categoria VARCHAR(20) NOT NULL,
                    nombre VARCHAR(100) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL,
                    existencia INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL
                )
                """);
            String restriccionCantidad = forzarFalloMovimiento ? ", CHECK (cantidad < 0)" : "";
            st.execute("""
                CREATE TABLE movimiento_inventario (
                    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_producto INTEGER NOT NULL,
                    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    tipo VARCHAR(15) NOT NULL,
                    cantidad INTEGER NOT NULL,
                    existencia_resultante INTEGER NOT NULL
                %s)
                """.formatted(restriccionCantidad));
            st.execute("""
                INSERT INTO producto (id_producto, codigo, categoria, nombre, precio, existencia)
                VALUES (1, 'SAN001', 'SANDWICH', 'Sándwich', 25.00, 5)
                """);
        }
        return conexion;
    }

    private InventarioServicio servicio(Connection conexion) {
        return new InventarioServicio(
            conexion,
            new ProductoDAOImpl(conexion),
            new MovimientoInventarioDAOImpl(conexion)
        );
    }

    private int existencia(Connection conexion) throws Exception {
        try (Statement st = conexion.createStatement();
             ResultSet rs = st.executeQuery("SELECT existencia FROM producto WHERE id_producto = 1")) {
            rs.next();
            return rs.getInt(1);
        }
    }

    private int cantidadMovimientos(Connection conexion) throws Exception {
        try (Statement st = conexion.createStatement();
             ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM movimiento_inventario")) {
            rs.next();
            return rs.getInt(1);
        }
    }
}
