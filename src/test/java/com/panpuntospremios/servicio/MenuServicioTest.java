package com.panpuntospremios.servicio;

import com.panpuntospremios.dao.MenuDAO;
import com.panpuntospremios.dao.MenuDAOImpl;
import com.panpuntospremios.dao.ProductoDAOImpl;
import com.panpuntospremios.excepcion.ValidacionException;
import com.panpuntospremios.modelo.Menu;
import com.panpuntospremios.modelo.Producto;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class MenuServicioTest {
    private Connection conexion;
    private MenuDAO menuDAO;
    private MenuServicio servicio;
    private List<Producto> productos;

    @AfterEach
    void cerrarConexion() throws Exception {
        if (conexion != null) {
            conexion.close();
        }
    }

    @BeforeEach
    void preparar() throws Exception {
        conexion = DriverManager.getConnection("jdbc:h2:mem:menus;MODE=Oracle;DB_CLOSE_DELAY=-1");
        try (Statement st = conexion.createStatement()) {
            st.execute("DROP TABLE IF EXISTS menu_detalle");
            st.execute("DROP TABLE IF EXISTS menu");
            st.execute("DROP TABLE IF EXISTS producto");
            st.execute("""
                CREATE TABLE producto (
                    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo VARCHAR(20) NOT NULL UNIQUE,
                    categoria VARCHAR(20) NOT NULL,
                    nombre VARCHAR(100) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL,
                    existencia INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL
                )
                """);
            st.execute("""
                CREATE TABLE menu (
                    id_menu INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo VARCHAR(20) NOT NULL UNIQUE,
                    nombre VARCHAR(100) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL
                )
                """);
            st.execute("""
                CREATE TABLE menu_detalle (
                    id_menu INTEGER NOT NULL,
                    id_producto INTEGER NOT NULL,
                    rol VARCHAR(20) NOT NULL,
                    PRIMARY KEY (id_menu, id_producto),
                    FOREIGN KEY (id_menu) REFERENCES menu(id_menu),
                    FOREIGN KEY (id_producto) REFERENCES producto(id_producto)
                )
                """);
            st.execute("""
                INSERT INTO producto (codigo, categoria, nombre, precio) VALUES
                ('SAN001', 'SANDWICH', 'Sándwich', 25.00),
                ('BEB001', 'BEBIDA', 'Bebida', 8.00),
                ('ACO001', 'ACOMPANAMIENTO', 'Papas', 10.00),
                ('SAN002', 'SANDWICH', 'Otro sándwich', 27.00)
                """);
        }
        productos = new ProductoDAOImpl(conexion).listarActivos();
        menuDAO = new MenuDAOImpl(conexion);
        servicio = new MenuServicio(conexion, menuDAO);
    }

    @Test
    void registraYRecuperaMenuConUnaCategoriaDeCadaTipo() throws Exception {
        Menu menu = menuValido();

        servicio.registrar(menu);

        List<Menu> menus = servicio.listarActivos();
        assertEquals(1, menus.size());
        assertEquals(3, menus.get(0).getComponentes().size());
        assertEquals(new BigDecimal("37.00"), menus.get(0).getPrecio());
    }

    @Test
    void rechazaMenuConCategoriasRepetidas() {
        Menu menu = new Menu(0, "MEN002", "Menú inválido", new BigDecimal("40.00"), true);
        menu.setComponentes(List.of(
            producto("SAN001"),
            producto("SAN002"),
            producto("BEB001")
        ));

        assertThrows(ValidacionException.class, () -> servicio.registrar(menu));
    }

    @Test
    void actualizaYDesactivaMenu() throws Exception {
        servicio.registrar(menuValido());
        Menu guardado = servicio.listarActivos().get(0);
        guardado.setNombre("Menú actualizado");
        guardado.setPrecio(new BigDecimal("39.50"));

        servicio.actualizar(guardado);
        Menu actualizado = menuDAO.buscarPorCodigo("MEN001");
        assertEquals("Menú actualizado", actualizado.getNombre());
        assertEquals(new BigDecimal("39.50"), actualizado.getPrecio());

        servicio.desactivar(actualizado.getIdMenu());
        assertTrue(servicio.listarActivos().isEmpty());
    }

    private Menu menuValido() {
        Menu menu = new Menu(0, "MEN001", "Menú completo", new BigDecimal("37.00"), true);
        menu.setComponentes(List.of(
            producto("SAN001"),
            producto("BEB001"),
            producto("ACO001")
        ));
        return menu;
    }

    private Producto producto(String codigo) {
        return productos.stream()
            .filter(producto -> codigo.equals(producto.getCodigo()))
            .findFirst()
            .orElseThrow();
    }
}
