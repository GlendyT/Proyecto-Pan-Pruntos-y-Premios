package com.panpuntospremios.servicio;

import com.panpuntospremios.dao.*;
import com.panpuntospremios.excepcion.StockInsuficienteException;
import com.panpuntospremios.modelo.*;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class PedidoServicioTest {
    private Connection conexion;
    private ProductoDAO productoDAO;
    private PedidoServicio pedidoServicio;

    @BeforeEach
    void preparar() throws Exception {
        conexion = DriverManager.getConnection("jdbc:h2:mem:pedidos;MODE=Oracle;DB_CLOSE_DELAY=-1");
        try (Statement st = conexion.createStatement()) {
            st.execute("DROP TABLE IF EXISTS pedido_detalle");
            st.execute("DROP TABLE IF EXISTS pedido");
            st.execute("DROP TABLE IF EXISTS cliente");
            st.execute("DROP TABLE IF EXISTS producto");
            st.execute("""
                CREATE TABLE cliente (
                    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    identificador VARCHAR(20) NOT NULL UNIQUE,
                    nombre VARCHAR(100) NOT NULL,
                    telefono VARCHAR(20),
                    email VARCHAR(100),
                    saldo_puntos INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL,
                    fecha_registro DATE DEFAULT CURRENT_DATE NOT NULL
                )
                """);
            st.execute("""
                CREATE TABLE producto (
                    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo VARCHAR(20) NOT NULL UNIQUE,
                    categoria VARCHAR(20) NOT NULL,
                    nombre VARCHAR(100) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL,
                    existencia INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL
                )
                """);
            st.execute("""
                CREATE TABLE pedido (
                    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_cliente INTEGER NOT NULL,
                    fecha DATE DEFAULT CURRENT_DATE NOT NULL,
                    estado VARCHAR(15) DEFAULT 'PENDIENTE' NOT NULL,
                    total DECIMAL(10,2) DEFAULT 0 NOT NULL,
                    puntos_generados INTEGER DEFAULT 0 NOT NULL,
                    metodo_pago VARCHAR(10),
                    referencia_pago VARCHAR(50)
                )
                """);
            st.execute("""
                CREATE TABLE pedido_detalle (
                    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_pedido INTEGER NOT NULL,
                    tipo_item VARCHAR(10) NOT NULL,
                    id_producto INTEGER,
                    id_menu INTEGER,
                    cantidad INTEGER NOT NULL,
                    precio_unitario DECIMAL(10,2) NOT NULL,
                    subtotal DECIMAL(10,2) NOT NULL,
                    puntos INTEGER DEFAULT 0 NOT NULL
                )
                """);
            st.execute("INSERT INTO cliente (identificador, nombre) VALUES ('CLI001', 'Juan Perez')");
            st.execute("INSERT INTO producto (codigo, categoria, nombre, precio, existencia) VALUES ('SAN001', 'SANDWICH', 'Sandwich de pollo', 25.00, 5)");
            st.execute("INSERT INTO producto (codigo, categoria, nombre, precio, existencia) VALUES ('BEB001', 'BEBIDA', 'Gaseosa', 8.00, 3)");
        }
        productoDAO = new ProductoDAOImpl(conexion);
        pedidoServicio = new PedidoServicio(new PedidoDAOImpl(conexion), productoDAO, conexion);
    }

    @AfterEach
    void cerrar() throws Exception {
        conexion.close();
    }

    @Test
    void creaUnPedidoConProductoIndividual() throws Exception {
        Producto sandwich = productoDAO.buscarPorCodigo("SAN001");
        ItemVenta item = new ProductoIndividual(sandwich, 2);
        Pedido pedido = new Pedido(0, 1, null, "PENDIENTE", item.calcularSubtotal(), item.calcularPuntos(), null, null);

        int idPedido = pedidoServicio.crearPedido(pedido, List.of(item));

        assertTrue(idPedido > 0);
        List<PedidoDetalle> detalle = pedidoServicio.listarDetalle(idPedido);
        assertEquals(1, detalle.size());
        assertEquals(2, detalle.get(0).getCantidad());
        assertEquals(4, detalle.get(0).getPuntos());
    }

    @Test
    void rechazaPedidoConStockInsuficiente() throws Exception {
        Producto sandwich = productoDAO.buscarPorCodigo("SAN001");
        ItemVenta item = new ProductoIndividual(sandwich, 10); // hay solo 5
        Pedido pedido = new Pedido(0, 1, null, "PENDIENTE", item.calcularSubtotal(), item.calcularPuntos(), null, null);

        assertThrows(StockInsuficienteException.class,
            () -> pedidoServicio.crearPedido(pedido, List.of(item)));
    }

    @Test
    void rechazaPedidoVacio() {
        Pedido pedido = new Pedido(0, 1, null, "PENDIENTE", BigDecimal.ZERO, 0, null, null);

        assertThrows(IllegalArgumentException.class,
            () -> pedidoServicio.crearPedido(pedido, List.of()));
    }

    @Test
    void anulaPedidoPendiente() throws Exception {
        Producto sandwich = productoDAO.buscarPorCodigo("SAN001");
        ItemVenta item = new ProductoIndividual(sandwich, 1);
        Pedido pedido = new Pedido(0, 1, null, "PENDIENTE", item.calcularSubtotal(), item.calcularPuntos(), null, null);

        int idPedido = pedidoServicio.crearPedido(pedido, List.of(item));
        pedidoServicio.anular(idPedido);

        Pedido anulado = pedidoServicio.buscarPorId(idPedido);
        assertEquals("ANULADO", anulado.getEstado());
    }

    @Test
    void rechazaAnularPedidoNoExistente() {
        assertThrows(IllegalArgumentException.class,
            () -> pedidoServicio.anular(9999));
    }
}
