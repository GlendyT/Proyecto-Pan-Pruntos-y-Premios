package com.panpuntospremios.servicio;

import com.panpuntospremios.dao.ProductoDAO;
import com.panpuntospremios.dao.ProductoDAOImpl;
import com.panpuntospremios.excepcion.ValidacionException;
import com.panpuntospremios.modelo.Producto;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class ProductoServicioTest {
    private Connection conexion;
    private ProductoDAO dao;
    private ProductoServicio servicio;

    @BeforeEach
    void preparar() throws Exception {
        conexion = DriverManager.getConnection("jdbc:h2:mem:productos;MODE=Oracle;DB_CLOSE_DELAY=-1");
        try (Statement st = conexion.createStatement()) {
            st.execute("DROP TABLE IF EXISTS producto");
            st.execute("""
                CREATE TABLE producto (
                    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo VARCHAR(20) NOT NULL UNIQUE,
                    categoria VARCHAR(20) NOT NULL,
                    nombre VARCHAR(100) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL,
                    existencia INTEGER DEFAULT 0 NOT NULL,
                    activo CHAR(1) DEFAULT 'S' NOT NULL
                )
                """);
        }
        dao = new ProductoDAOImpl(conexion);
        servicio = new ProductoServicio(dao);
    }

    @AfterEach
    void cerrar() throws Exception {
        conexion.close();
    }

    @Test
    void registraActualizaYDesactivaProducto() throws Exception {
        servicio.registrar(producto("SAN100", "SANDWICH", "Sándwich inicial", "20.00"));
        Producto guardado = dao.buscarPorCodigo("SAN100");
        Producto editado = new Producto(
            guardado.getIdProducto(),
            guardado.getCodigo(),
            guardado.getCategoria(),
            "Sándwich actualizado",
            new BigDecimal("22.50"),
            guardado.getExistencia(),
            true
        );

        servicio.actualizar(editado);

        Producto actualizado = dao.buscarPorCodigo("SAN100");
        assertEquals("Sándwich actualizado", actualizado.getNombre());
        assertEquals(new BigDecimal("22.50"), actualizado.getPrecio());

        servicio.desactivar(actualizado.getIdProducto());
        assertTrue(servicio.listarActivos().isEmpty());
    }

    @Test
    void rechazaCodigoDuplicadoYPrecioNegativo() throws Exception {
        servicio.registrar(producto("BEB100", "BEBIDA", "Bebida", "8.00"));

        assertThrows(
            ValidacionException.class,
            () -> servicio.registrar(producto("BEB100", "BEBIDA", "Otra bebida", "9.00"))
        );
        assertThrows(
            ValidacionException.class,
            () -> servicio.registrar(producto("ACO100", "ACOMPANAMIENTO", "Papas", "-1.00"))
        );
    }

    private Producto producto(String codigo, String categoria, String nombre, String precio) {
        return new Producto(0, codigo, categoria, nombre, new BigDecimal(precio), 0, true);
    }
}
